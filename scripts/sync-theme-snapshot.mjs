#!/usr/bin/env node
/**
 * Refresh preview/theme-fallback.css from a DeepSeek Harness install.
 *
 * The preview harness must render against the host's real palette; this script
 * copies the two token sheets and keeps every custom property with its
 * selector, so the light (`body`) and dark (`body[data-ds-dark-theme]`)
 * scopes stay intact. It refuses to write a snapshot that lost either palette.
 *
 * Usage:
 *   node scripts/sync-theme-snapshot.mjs <theme-styles-dir>
 *   DSH_THEME_CSS_DIR=<theme-styles-dir> npm run theme:snapshot
 *
 * The directory is the one build-preview uses:
 *   node_modules/@deepseek-ai/dsh-client-ui-theme/src/styles
 * inside a DSH installation.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { readThemeTokens, parseTokenRules, themeSheets } from "./theme-tokens.mjs";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = process.argv[2] ?? process.env.DSH_THEME_CSS_DIR;
if (dir === undefined || dir === "") {
  console.error("usage: node scripts/sync-theme-snapshot.mjs <dsh-ui-theme/styles dir>");
  console.error("       (or set DSH_THEME_CSS_DIR)");
  process.exit(1);
}

const css = readThemeTokens(resolve(dir));
const rules = parseTokenRules(css);
const light = rules.get("body");
const dark = rules.get("body[data-ds-dark-theme]");
const REQUIRED = ["--dsw-alias-bg-base", "--dsw-alias-label-primary", "--dsw-alias-brand-primary", "--dsw-menu-surface-fill"];

function assertPalette(scope, tokens) {
  if (tokens === undefined) throw new Error(`theme: no ${scope} rule in the extracted sheet`);
  const missing = REQUIRED.filter((token) => !tokens.has(token));
  if (missing.length > 0) throw new Error(`theme: ${scope} lost semantic aliases: ${missing.join(", ")}`);
}

assertPalette("body", light);
assertPalette("body[data-ds-dark-theme]", dark);

const pluginVersion = (() => {
  try {
    return JSON.parse(readFileSync(resolve(rootDir, "package.json"), "utf8")).version;
  } catch {
    return "unknown";
  }
})();
const hostVersion = (() => {
  try {
    // <dsh>/node_modules/@deepseek-ai/dsh-client-ui-theme/src/styles -> package.json
    return JSON.parse(readFileSync(resolve(dir, "../../package.json"), "utf8")).version ?? "unknown";
  } catch {
    return "unknown";
  }
})();

const header = `/*
 * Offline token snapshot for preview pages (Harbor ${pluginVersion}).
 *
 * GENERATED by scripts/sync-theme-snapshot.mjs from
 * @deepseek-ai/dsh-client-ui-theme/src/styles (base.css + design-platform.css)
 * of @deepseek-ai/dsh-client-ui-theme ${hostVersion}. Do not edit by hand;
 * rerun the script after the host theme changes.
 *
 * Both palettes are kept with their host selectors: light under \`body\`,
 * dark under \`body[data-ds-dark-theme]\`. Flattening them merges the dark
 * overrides into the light scope and silently drops every alias.
 */
`;
writeFileSync(resolve(rootDir, "preview/theme-fallback.css"), header + css + "\n", "utf8");
console.log(`theme: wrote preview/theme-fallback.css (${css.length} bytes) from ${themeSheets(resolve(dir)).join(", ")}`);
